def rank_axes(job: str, industry: str) -> list[dict]:
    rows = []
    for ax in AXIS_ORDER:
        jw, iw, why = SALIENCE[ax]
        # Job describes the daily work, industry modulates it -> job weight x1.5; ties: job weight, then order.
        rows.append({"axis": ax, "name": AXES[ax]["name"], "job_w": jw[job], "industry_w": iw[industry], "total": 1.5 * jw[job] + iw[industry], "why": why})
    return sorted(rows, key=lambda r: (-r["total"], -r["job_w"], AXIS_ORDER.index(r["axis"])))


def pick_axis(job: str, industry: str) -> str:
    return rank_axes(job, industry)[0]["axis"]
