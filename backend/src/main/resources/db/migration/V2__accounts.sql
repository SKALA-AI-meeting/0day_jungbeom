-- Candidate accounts (회원가입). The agent screens each new account (ACCOUNT_REVIEW task):
-- PENDING_REVIEW -> ACTIVE | REJECTED, or REVIEW_ERROR when the agent could not finish (goes to the admin inbox).
CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    invite_id BIGINT REFERENCES invites(id),
    email VARCHAR(200) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    nickname VARCHAR(20) NOT NULL,
    desired_job VARCHAR(20) NOT NULL,
    industry VARCHAR(20),
    experience_years INT NOT NULL,
    bio TEXT,
    consent BOOLEAN NOT NULL,
    status VARCHAR(20) NOT NULL,
    review_json TEXT,
    reviewed_by VARCHAR(80),
    reviewed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

ALTER TABLE sessions ADD COLUMN account_id BIGINT REFERENCES accounts(id);
ALTER TABLE ai_tasks ADD COLUMN account_id BIGINT REFERENCES accounts(id);
CREATE INDEX ix_accounts_company ON accounts(company_id);
CREATE INDEX ix_sessions_account ON sessions(account_id);
