-- Business data, task history and SSE event log. JSON payloads are stored as TEXT (portable PostgreSQL / H2).
CREATE TABLE companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    email VARCHAR(200) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE invites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    token VARCHAR(64) NOT NULL UNIQUE,
    alias VARCHAR(40),
    email VARCHAR(200),
    reusable BOOLEAN NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE,
    used_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE sessions (
    id VARCHAR(32) PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    invite_id BIGINT REFERENCES invites(id),
    alias VARCHAR(40) NOT NULL,
    scenario_id VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL,
    milestone_idx INT NOT NULL,
    turns_in_milestone INT NOT NULL,
    condition_json TEXT,
    choice_json TEXT,
    milestone_log_json TEXT,
    notes TEXT,
    report_json TEXT,
    report_status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(32) NOT NULL REFERENCES sessions(id),
    idx INT NOT NULL,
    speaker VARCHAR(10) NOT NULL,
    text TEXT NOT NULL,
    milestone VARCHAR(20) NOT NULL,
    choice VARCHAR(10),
    sources_json TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_message UNIQUE (session_id, idx)
);

CREATE TABLE observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(32) NOT NULL REFERENCES sessions(id),
    obs_key VARCHAR(40) NOT NULL,
    competency VARCHAR(5) NOT NULL,
    milestone VARCHAR(20) NOT NULL,
    behavior TEXT NOT NULL,
    quote TEXT NOT NULL,
    signal VARCHAR(10) NOT NULL,
    msg_idx INT NOT NULL
);

CREATE TABLE detections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(32) NOT NULL REFERENCES sessions(id),
    msg_idx INT NOT NULL,
    doc_json TEXT NOT NULL,
    CONSTRAINT uq_detection UNIQUE (session_id, msg_idx)
);

CREATE TABLE ai_tasks (
    id VARCHAR(36) PRIMARY KEY,
    session_id VARCHAR(32) REFERENCES sessions(id),
    company_id BIGINT REFERENCES companies(id),
    type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    thread_id VARCHAR(80) NOT NULL,
    payload_json TEXT,
    result_json TEXT,
    error TEXT,
    trace_json TEXT,
    attempts INT NOT NULL,
    created_by VARCHAR(80) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE task_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id VARCHAR(36) NOT NULL REFERENCES ai_tasks(id),
    seq INT NOT NULL,
    type VARCHAR(30) NOT NULL,
    data_json TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_messages_session ON messages(session_id);
CREATE INDEX ix_observations_session ON observations(session_id);
CREATE INDEX ix_tasks_session ON ai_tasks(session_id);
CREATE INDEX ix_task_events_task ON task_events(task_id);
