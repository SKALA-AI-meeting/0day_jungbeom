-- Shared work items (같이 확인할 과제: design doc, result table, code) seeded by the agent at START,
-- and the candidate's markups on them. The agent's planted checkpoints are never stored here.
CREATE TABLE session_artifacts (
    session_id VARCHAR(32) NOT NULL REFERENCES sessions(id),
    artifact_id VARCHAR(16) NOT NULL,
    ord INT NOT NULL,
    kind VARCHAR(10) NOT NULL,
    title VARCHAR(80) NOT NULL,
    owner VARCHAR(10) NOT NULL,
    status VARCHAR(20),
    summary VARCHAR(160),
    lang VARCHAR(20),
    body TEXT NOT NULL,
    PRIMARY KEY (session_id, artifact_id)
);

-- Anchor: a line range (1-based, inclusive) and/or a quoted substring of the body.
-- msg_idx = number of messages when the markup was made (the idx the next message gets).
CREATE TABLE annotations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(32) NOT NULL REFERENCES sessions(id),
    artifact_id VARCHAR(16) NOT NULL,
    line_start INT,
    line_end INT,
    quote VARCHAR(300),
    kind VARCHAR(10) NOT NULL,
    text VARCHAR(500) NOT NULL,
    msg_idx INT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_annotations_session ON annotations(session_id);
